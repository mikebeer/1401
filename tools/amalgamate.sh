#!/bin/sh
# amalgamate.sh OUTDIR - one C89 source per CMS command:
#   IBM1401.C  = bcd.h i1401.h bcd.c cpu.c io.c disk.c ibm1401.c
#   AUTOCODR.C = bcd.h bcd.c autocoder.c
# (CMS's CC EXEC compiles one file into one MODULE.)  The #include of
# the local headers is dropped; system headers stay.
set -e
B=$(cd "$(dirname "$0")/.." && pwd)
O=${1:-$B/build/cms}
mkdir -p "$O"
cat_src() {
  for f in "$@"; do
    echo "/* ==== $(basename $f) ==== */"
    grep -v '^#include "' "$B/src/$f"
  done
}
{ echo "/* IBM1401 C - IBM 1401 emulator for VM/370plus (mikebeer/1401),"
  echo "   generated by tools/amalgamate.sh from src/; do not edit */"
  cat_src version.h bcd.h i1401.h bcd.c cpu.c io.c disk.c ibm1401.c; } > "$O/IBM1401.C"
{ echo "/* AUTOCODR C - IBM 1401 Autocoder for VM/370plus (mikebeer/1401),"
  echo "   generated by tools/amalgamate.sh from src/; do not edit */"
  cat_src version.h bcd.h bcd.c autocoder.c; } > "$O/AUTOCODR.C"
echo "amalgamate: $O/IBM1401.C $O/AUTOCODR.C"
